"""Inspect saved outputs and re-export figures without touching prior results."""
import csv
import json
from pathlib import Path
import re
import sqlite3
from contextlib import closing
import zipfile

from . import __version__, code_fingerprint
from .util import atomic_text, digest, now, write_json


def read_jobs(cfg):
    database = cfg.paths['state'] / 'jobs.sqlite3'
    if not database.exists():
        return []
    with closing(sqlite3.connect(database.as_uri() + '?mode=ro', uri=True)) as connection:
        connection.row_factory = sqlite3.Row
        return [dict(row) for row in connection.execute('SELECT * FROM jobs ORDER BY updated_at, id')]


def latest_jobs(jobs):
    latest = {}
    for job in jobs:
        if job['status'] == 'completed':
            latest[job['source']] = job
    return list(latest.values())


def local_result(cfg, job):
    stored = Path(job.get('result_path') or '')
    if stored.is_file() and cfg.paths['analysis'] in stored.resolve().parents:
        return stored
    candidates = [cfg.paths['analysis'] / 'runs' / job['id'] / 'result.json']
    candidates.extend((cfg.paths['analysis'] / 'runs').glob('v*/' + job['id'] + '/result.json'))
    return next((p for p in candidates if p.is_file()), None)


def contained(root, relative):
    target = (root / str(relative)).resolve()
    return target if root.resolve() in target.parents else None


def audit_results(cfg):
    """Only new audit artifacts are written; DB, notes, figures and inputs are read."""
    from .pipeline import candidates
    jobs = read_jobs(cfg)
    latest = latest_jobs(jobs)
    issues, files, metrics, coverage = [], [], [], []

    def issue(code, source, detail):
        issues.append({'code': code, 'source': source, 'detail': detail})

    for key in ('inbox', 'vault'):
        if not cfg.paths[key].is_dir():issue(key + '_root_missing', '', '현재 PC에서 설정 폴더를 찾지 못했습니다.')
    completed = {(j['source'], j['source_hash']) for j in jobs if j['status'] == 'completed'}
    for source in candidates(cfg):
        relative = source.relative_to(cfg.paths['inbox']).as_posix()
        try:
            content_hash = digest(source)
            exists = (relative, content_hash) in completed
            coverage.append({'source': relative, 'source_sha256': content_hash, 'saved_completed_job': exists})
            if not exists:
                issue('input_without_completed_result', relative, '현재 원본 내용에 대응하는 완료 작업이 없습니다.')
        except OSError as error:
            issue('input_unreadable', relative, type(error).__name__)
    for job in latest:
        source = job['source']
        result_path = local_result(cfg, job)
        if result_path is None:
            issue('result_missing', source, '현재 PC의 Analysis에서 result.json을 찾지 못했습니다.')
            continue
        try:
            summary = json.loads(result_path.read_text(encoding='utf-8-sig'))
        except (OSError, ValueError):
            issue('result_invalid_json', source, 'result.json을 읽을 수 없습니다.')
            continue
        original = contained(cfg.paths['inbox'], source)
        if not original or not original.is_file():
            issue('original_missing', source, '현재 Inbox에서 원본을 찾지 못했습니다.')
        elif any(c['source'] == source and c['source_sha256'] != summary.get('source_sha256') for c in coverage):
            issue('original_hash_changed', source, '저장 결과와 현재 원본 내용이 다릅니다.')
        context = summary.get('research_context', {})
        groups = summary.get('groups', [])
        fields = context.get('fields', {})
        metadata_status = context.get('metadata_status', 'legacy_unreviewed')
        if metadata_status != 'confirmed':
            issue('metadata_review_needed', source, metadata_status)
        if any(g.get('units_review_required') for g in groups):
            issue('units_review_needed', source, 'SI 가정 후보가 있으며 단위 확인이 필요합니다.')
        from .render import vault_locations
        note_relative = summary.get('vault_note_relative_path') or vault_locations(summary)[0]
        note = contained(cfg.paths['vault'], note_relative)
        if not note or not note.is_file():
            issue('note_missing', source, note_relative)
        else:
            for link in re.findall(r'\[\[([^\]|]+)', note.read_text(encoding='utf-8-sig')):
                # Links generated by this tool are Vault-relative file paths.
                target = contained(cfg.paths['vault'], link.split('#', 1)[0])
                if not target or not target.exists():
                    issue('note_link_missing', source, link)
        required = ['normalized.csv', 'curves.csv', 'metrics.csv', 'fit_results.csv']
        if summary.get('schema_version', 0) >= 4:
            required += ['parsed_points.csv', 'observable_metrics.csv', 'model_diagnostics.csv']
        for name in required + summary.get('figures', []):
            target = contained(result_path.parent, name)
            if not target or not target.is_file():
                issue('output_missing', source, name)
        ids = [g.get('group_id') for g in groups]
        if len(ids) != len(set(ids)):
            issue('duplicate_group_id', source, '그룹 ID 중복')
        for group in groups:
            for m in group.get('rr_series', []):
                if m.get('evaluation_abs_vd_v') is None or m.get('unit') != '1':
                    issue('rr_condition_or_unit_missing', source, group['group_id'])
            raw = group.get('transfer_metrics', {}).get('raw_peak_abs', {})
            if raw.get('endpoint') and raw.get('metric_status') == 'valid':
                issue('endpoint_peak_marked_valid', source, group['group_id'])
        metric_path = result_path.parent / 'observable_metrics.csv'
        if metric_path.is_file():
            try:
                with metric_path.open(encoding='utf-8-sig', newline='') as stream:
                    for m in csv.DictReader(stream):
                        metrics.append({key: m.get(key) for key in ('source_relative_path', 'source_sha256', 'group_id', 'metric', 'value', 'candidate_value_assuming_si', 'unit', 'evaluation_abs_vd_v', 'evaluation_vd_v', 'fixed_vd_v', 'vg_v', 'direction', 'gate_block_id', 'metric_status', 'reason')})
            except (OSError, ValueError):
                issue('metric_csv_unreadable', source, 'observable_metrics.csv')
        measurement_points = None
        if (result_path.parent / 'normalized.csv').is_file():
            with (result_path.parent / 'normalized.csv').open(encoding='utf-8-sig', newline='') as stream:
                measurement_points = max(0, sum(1 for row in csv.reader(stream)) - 1)
        files.append({'source': source, 'job_id': job['id'], 'source_sha256': summary.get('source_sha256'),
                      'analysis_version': summary.get('version'), 'analysis_code_sha256': summary.get('code_sha256'),
                      'groups': len(groups), 'measurement_points': measurement_points, 'branch_points_including_shared_turns': sum(g.get('n', 0) for g in groups),
                      'legacy_qc': summary.get('qc', {}).get('overall'), 'metadata_status': metadata_status,
                      'fields': fields, 'parse_status': summary.get('statuses', {}).get('parse_status'),
                      'figures': summary.get('figures', [])})
    current_hashes = {(c['source'], c['source_sha256']) for c in coverage}
    failed = [j for j in jobs if (j['source'], j['source_hash']) in current_hashes and j['status'] in ('failed', 'processing') and not any(k['source'] == j['source'] and k['source_hash'] == j['source_hash'] and k['updated_at'] >= j['updated_at'] for k in latest)]
    for job in failed:
        issue('job_not_completed', job['source'], job['status'])
    stamp = now(cfg).strftime('%Y%m%d-%H%M%S-%f')
    directory = cfg.paths['analysis'] / 'audits' / ('v' + __version__) / stamp
    directory.mkdir(parents=True, exist_ok=False)
    report = {'tool_version': __version__, 'tool_code_sha256': code_fingerprint(), 'created_at': now(cfg).isoformat(),
              'scope': 'current input coverage and latest completed result per source', 'inputs': coverage, 'files': files,
              'issues': issues, 'summary': {'input_files': len(coverage), 'covered_inputs': sum(c['saved_completed_job'] for c in coverage),
                                          'latest_completed_results': len(files), 'groups': sum(f['groups'] for f in files),
                                          'measurement_points': sum(f['measurement_points'] for f in files if f['measurement_points'] is not None), 'issues': len(issues)},
              'external_api_calls': 0, 'originals_or_saved_results_modified': False,
              'limitations': ['구조·해시·링크·상태 점검이며 모든 지표를 원본에서 독립 재계산한 검증은 아닙니다.', 'PNG 픽셀의 음수 글리프와 실제 실험 이력은 자동 인증하지 않습니다.']}
    write_json(directory / 'audit.json', report)
    fields_out = list(metrics[0]) if metrics else ['source_relative_path', 'group_id', 'metric', 'value', 'unit', 'metric_status']
    with (directory / 'metrics.csv').open('w', encoding='utf-8-sig', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=fields_out); writer.writeheader(); writer.writerows(metrics)
    lines = ['# 저장 결과 점검', '', f"입력 {len(coverage)}개 중 완료 기록 {report['summary']['covered_inputs']}개; 최신 결과 {len(files)}개 / {report['summary']['groups']}곡선.",
             '', '이 점검은 파싱/추출 완료와 과학적 확인 상태를 구별합니다. 원본·기존 노트·CSV·PNG·DB를 수정하지 않았습니다.', '', '## 검토 사항', '']
    lines += [f"- {i['source']}: {i['code']} / {i['detail']}" for i in issues] or ['- 자동 구조 점검에서 문제를 찾지 못했습니다. 실험 조건의 신뢰성은 별도 검토가 필요합니다.']
    lines += ['', 'ZIP에는 원본 측정파일·원시 측정점·API 키·활성 설정·DB·이미지가 없습니다. 파일명과 요약 지표·확인 상태는 포함됩니다.', '', *report['limitations']]
    atomic_text(directory / 'report.md', '\n'.join(lines) + '\n')
    bundle = directory / 'result-audit.zip'
    with zipfile.ZipFile(bundle, 'w', zipfile.ZIP_DEFLATED) as archive:
        for name in ('audit.json', 'metrics.csv', 'report.md'):
            archive.write(directory / name, name)
    return {'report': str(directory / 'report.md'), 'bundle': str(bundle), **report['summary']}


def refresh_plots(cfg, sources=None):
    """Export immutable plot revisions from cached curves; no parse/refit/AI."""
    import pandas as pd
    from .render import plots, vault_locations
    from .store import lock
    records = []
    with lock(cfg):
        for job in latest_jobs(read_jobs(cfg)):
            if sources is not None and job['source'] not in sources:
                continue
            result = local_result(cfg, job)
            if not result or not (result.parent / 'curves.csv').is_file():
                records.append({'source': job['source'], 'status': 'skipped', 'reason': 'cached_result_or_curves_missing'})
                continue
            summary = json.loads(result.read_text(encoding='utf-8-sig'))
            curves = pd.read_csv(result.parent / 'curves.csv', float_precision='round_trip')
            stamp = now(cfg).strftime('%Y%m%d-%H%M%S-%f')
            relative = f'Attachments/v{__version__}/PlotRevisions/{job["id"]}/{stamp}'
            destination = cfg.paths['vault'] / relative
            destination.mkdir(parents=True, exist_ok=False)
            figures = plots(curves, summary, destination)
            note = cfg.paths['vault'] / f'Experiments/v{__version__}/그래프 갱신/{job["id"]}_{stamp}.md'
            original_note = summary.get('vault_note_relative_path') or vault_locations(summary)[0]
            lines = ['# 그래프 표시 갱신', '', f'원본 결과: [[{original_note}]]', '',
                     '저장된 curves.csv와 피팅 결과로 음수 표시를 수정했습니다. 수치 재분석·재피팅·AI 호출 없이 기존 결과를 보존했습니다.', '',
                     f'기존 분석 버전: {summary.get("version")}; 그래프 버전: {__version__}',
                     f'원본 측정 SHA-256: {summary.get("source_sha256")}',
                     f'이전 curves.csv SHA-256: {digest(result.parent / "curves.csv")}', '']
            lines += [f'![[{relative}/{name}]]' for name in figures]
            atomic_text(note, '\n'.join(lines) + '\n')
            write_json(destination / 'revision.json', {'source': job['source'], 'source_sha256': summary.get('source_sha256'),
                'numeric_analysis_version': summary.get('version'), 'plot_version': __version__, 'plot_code_sha256': code_fingerprint(),
                'prior_curves_sha256': digest(result.parent / 'curves.csv'), 'refit': False, 'api_calls': 0, 'figures': figures})
            records.append({'source': job['source'], 'status': 'completed', 'figures': len(figures), 'note': str(note), 'folder': str(destination)})
    return {'files': records, 'completed': sum(r['status'] == 'completed' for r in records), 'refit': False, 'api_calls': 0}
